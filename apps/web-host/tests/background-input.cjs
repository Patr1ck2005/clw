'use strict';
// A real, unfocused Chromium renderer. No remote page or account is opened.
const {app,BrowserWindow,WebContentsView,session}=require('electron');
const assert=require('node:assert/strict');
const path=require('node:path'),fs=require('node:fs');
const input=require('../page-input.cjs');
const {dom}=require('../page-dom.cjs');
const {BrowserPool}=require('../browser-pool.cjs');
const dest=path.resolve(__dirname,'../../../.local/web-host-qa');
app.setPath('userData',path.join(dest,'input-profile'));
app.whenReady().then(async()=>{
  await session.defaultSession.setProxy({mode:'fixed_servers',proxyRules:'http://127.0.0.1:1',proxyBypassRules:'<-loopback>'});
  session.defaultSession.webRequest.onBeforeRequest((details,callback)=>callback({cancel:!details.url.startsWith('data:')}));
  const win=new BrowserWindow({show:false,webPreferences:{sandbox:true,nodeIntegration:false}});
  const pool=new BrowserPool({window:win,WebContentsView,partition:'input-test',allowedUrl:u=>u.startsWith('data:'),powerSaveBlocker:{start:()=>1,stop(){}}});
  const page=await pool.create('background','data:text/html,'+encodeURIComponent('<button style="position:absolute;left:20px;top:20px;width:200px;height:50px">Open</button><div id="prompt-textarea" contenteditable style="position:absolute;top:100px;width:400px;height:80px"></div><script>window.received={pointer:0,key:[]};document.querySelector("button").addEventListener("pointerdown",()=>received.pointer++);document.addEventListener("keydown",e=>received.key.push(e.key));</script>'));
  const view=page.view;await page.navigation;await page.viewportReady;
  await new Promise(resolve=>setTimeout(resolve,250));
  await input.evaluate(view.webContents,`(${input.domClick.toString()})(document.querySelector('button'))`);
  await view.webContents.executeJavaScript('document.querySelector("[contenteditable]").focus()');
  await input.insert(view.webContents,'Background α + x²');
  await input.key(view.webContents,'ArrowLeft');await input.key(view.webContents,'Escape');
  const observed=await view.webContents.executeJavaScript('({pointer:received.pointer,keys:received.key,text:document.querySelector("[contenteditable]").innerText,width:innerWidth,height:innerHeight})');
  assert.equal(observed.pointer,1);assert.equal(observed.text,'Background α + x²');assert.deepEqual(observed.keys,['ArrowLeft','Escape']);
  assert.equal(win.isVisible(),false);assert.equal(win.isFocused(),false);
  assert.ok(observed.width>=800);assert.ok(observed.height>=600);
  const inspect=(action,arg={})=>input.evaluate(view.webContents,`(${dom.toString()})(${JSON.stringify(action)},${JSON.stringify(arg)})`);
  assert.equal((await inspect('snapshot')).composing,false);
  await view.webContents.executeJavaScript('document.querySelector("[contenteditable]").innerText="";document.querySelector("[contenteditable]").dispatchEvent(new CompositionEvent("compositionstart",{bubbles:true,data:"拼"}))');
  assert.equal((await inspect('snapshot')).composing,true);
  await assert.rejects(inspect('focus-editor'));
  await view.webContents.executeJavaScript('document.querySelector("[contenteditable]").dispatchEvent(new CompositionEvent("compositionend",{bubbles:true,data:"拼"}))');
  assert.equal((await inspect('snapshot')).composing,false);
  await inspect('focus-editor');
  const plain='First paragraph\nSecond paragraph [CLW:fixture]';
  await inspect('insert-plain-text',{text:plain});
  assert.equal((await inspect('editor-text')).text,plain);
  const result={...observed,windowVisible:win.isVisible(),windowFocused:win.isFocused(),compositionGuard:true,plainTextReadback:true,realAccount:false,realModel:false,passed:true};
  fs.mkdirSync(dest,{recursive:true});fs.writeFileSync(path.join(dest,'background-input.json'),JSON.stringify(result,null,2));
  console.log(JSON.stringify(result));app.exit(0);
}).catch(error=>{console.error(error);app.exit(1);});
